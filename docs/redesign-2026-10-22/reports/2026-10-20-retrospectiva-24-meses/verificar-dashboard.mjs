import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { execFileSync } from 'node:child_process';

export async function verifyDashboard(page, dir, data, narrative, privateNames) {
  const model = JSON.parse(fs.readFileSync(path.join(dir, 'dashboard-data.json'), 'utf8'));
  assert.equal(model.prs.length, data.prs.length);
  assert.deepEqual(model.prs.filter(pr => pr.integrated).map(pr => pr.id).sort(), data.prs.filter(pr => pr.integrated).map(pr => pr.id).sort());
  assert.equal(model.repositories.reduce((sum, repo) => sum + repo.modules, 0), 159);
  assert.equal(model.repositories.reduce((sum, repo) => sum + repo.testFiles, 0), 2710);
  assert.equal(model.stories.length, narrative.stories.length);
  for (const chain of [...model.chains, ...model.ai]) for (const id of chain.stories) assert(model.stories.some(story => story.id === id));
  for (const observation of model.observations) {
    assert(data.prs.some(pr => pr.id === observation.ref && pr.url === observation.url));
    assert.equal(observation.reductionPercent, 100 * (1 - observation.after / observation.before));
    assert(observation.limit.length > 40);
  }
  for (const pr of model.prs) assert(/^20\d\d-\d\d-\d\d$/.test(pr.date));
  await page.goto(pathToFileURL(path.join(dir, 'dashboard.html')).href, { waitUntil: 'load' });
  await page.waitForFunction(() => window.dashboardApi);
  assert.equal(await page.locator('.dash-chart').count(), 22);
  assert.equal(await page.locator('.chart-data').count(), 22);
  assert.equal(await page.locator('.module-tile').count(), 42);
  assert.equal(await page.locator('.infra-dashboard>details').count(), 9);
  assert.equal(await page.locator('.proof-grid article').count(), 8);
  assert.equal(await page.locator('.value-stories article').count(), 6);
  assert.equal(await page.locator('.topbar [aria-current="page"]').innerText(), 'Dashboard');
  assert(!privateNames.test(await page.locator('body').innerText()));
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  assert.equal(await page.evaluate(() => window.dashboardApi.getFiltered().length), 2978);
  const monthly = await page.locator('[data-chart="1"] tbody tr').evaluateAll(rows => rows.map(row => [...row.querySelectorAll('td')].map(cell => cell.textContent)));
  assert.equal(monthly.length, 25);
  const parseNumber = value => Number(value.replaceAll('.', '').replace(',', '.'));
  assert.equal(monthly.reduce((sum, row) => sum + parseNumber(row.at(-1)), 0), 2840);
  const businessNumbers = await page.locator('#business-kpis b').allTextContents();
  assert.equal(businessNumbers[0], '54');
  const fixed = await page.locator('#architecture-kpis').innerText();
  await page.selectOption('#dash-repo', 'developy');
  assert.equal(await page.evaluate(() => window.dashboardApi.getFiltered().length), 335);
  assert.equal(await page.locator('#delivery-kpis .dash-kpi').nth(1).locator('b').innerText(), '328');
  assert.equal(await page.locator('#architecture-kpis').innerText(), fixed);
  assert(new URL(page.url()).hash.includes('repo=developy'));
  await page.selectOption('#dash-from', '2026-09');
  await page.selectOption('#dash-to', '2026-09');
  assert.equal(await page.locator('#delivery-kpis .dash-kpi').nth(1).locator('b').innerText(), '128');
  const downloadPromise = page.waitForEvent('download');
  await page.locator('#dash-export').click();
  const download = await downloadPromise;
  const downloadPath = await download.path();
  const csv = fs.readFileSync(downloadPath, 'utf8');
  assert(csv.includes('developy#')); assert(!csv.includes('wpp#'));
  assert.equal(csv.split('\r\n').length - 1, await page.evaluate(() => window.dashboardApi.getFiltered().length));
  await page.reload();
  assert.equal(await page.locator('#dash-repo').inputValue(), 'developy');
  assert.equal(await page.locator('#dash-from').inputValue(), '2026-09');
  await page.evaluate(() => window.dashboardApi.setState({ from: '2024-10', to: '2024-11' }));
  assert.equal(await page.evaluate(() => window.dashboardApi.getFiltered().length), 0);
  assert(!(await page.locator('#delivery-charts').innerHTML()).match(/NaN|Infinity/));
  await page.locator('#dash-reset').click();
  await page.locator('[data-chart="1"] .chart-data summary').click();
  assert.equal(await page.locator('[data-chart="1"] table').isVisible(), true);
  await page.locator('[data-chart="1"] .chart-data summary').click();
  const barLink = await page.locator('[data-chart="1"] svg a').last().getAttribute('href');
  assert(barLink.includes('Integrado')); assert(barLink.includes('month='));
  const brokenAnchors = await page.evaluate(() => [...document.querySelectorAll('a[href^="#"]')].map(anchor => anchor.getAttribute('href').slice(1)).filter(id => !document.getElementById(id)));
  assert.deepEqual(brokenAnchors, []);
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: path.join(dir, 'preview-dashboard.png') });
  await page.locator('#business-charts').scrollIntoViewIfNeeded();
  await page.screenshot({ path: path.join(dir, 'preview-dashboard-produto.png') });
  await page.locator('#efficiency-charts').scrollIntoViewIfNeeded();
  await page.screenshot({ path: path.join(dir, 'preview-dashboard-ganhos.png') });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.evaluate(() => window.scrollTo(0, 0));
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.screenshot({ path: path.join(dir, 'preview-dashboard-mobile.png') });
  for (const id of ['entregas', 'valor', 'arquitetura', 'confianca', 'ganhos', 'metodo']) {
    await page.locator('#' + id).scrollIntoViewIfNeeded();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, id);
  }
  await page.locator('#infra-cases details').first().locator('summary').click();
  assert.equal(await page.locator('#infra-cases details').first().locator('div').isVisible(), true);
  await page.setViewportSize({ width: 1440, height: 1100 });
  await page.pdf({ path: path.join(dir, 'dashboard.pdf'), format: 'A4', printBackground: true, preferCSSPageSize: true, displayHeaderFooter: true, headerTemplate: '<span></span>', footerTemplate: '<div style="width:100%;margin:0 13mm;font:8px sans-serif;color:#5a5468;display:flex;justify-content:space-between"><span>Catalisa · Dashboard e números</span><span><span class="pageNumber"></span> / <span class="totalPages"></span></span></div>' });
  const pdfPath = path.join(dir, 'dashboard.pdf');
  const pdfText = execFileSync('pdftotext', [pdfPath, '-'], { encoding: 'utf8' });
  assert(!privateNames.test(pdfText));
  assert(pdfText.includes('Memória de 28 serviços'));
  assert(pdfText.includes('2.840'));
  const pages = Number(execFileSync('pdfinfo', [pdfPath], { encoding: 'utf8' }).match(/Pages:\s+(\d+)/)[1]);
  return { page: 'dashboard', charts: 22, dataTables: 22, modules: 42, filtersVerified: true, emptyRangeVerified: true, csvVerified: true, mobileOverflow: false, privateNames: false, pdf: { file: 'dashboard.pdf', pages, bytes: fs.statSync(pdfPath).size, visibleClientNames: false, pageNumbers: true } };
}
