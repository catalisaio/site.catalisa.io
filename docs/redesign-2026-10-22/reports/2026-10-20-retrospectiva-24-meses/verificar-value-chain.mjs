import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { execFileSync } from 'node:child_process';
import { buildValueChain } from './value-chain-model.mjs';

export async function verifyValueChain(page, dir, privateNames) {
  const dashboard = JSON.parse(fs.readFileSync(path.join(dir, 'dashboard-data.json'), 'utf8'));
  const model = buildValueChain(dashboard);
  assert.equal(model.storyCount, 37);
  assert.equal(model.refs.length, 220);
  assert.deepEqual(model.chapters.map(stage => stage.refs.length), [38, 49, 46, 20, 42, 29]);
  assert.deepEqual(model.chapters.map(stage => stage.stories.length), [5, 7, 8, 3, 8, 6]);
  assert.equal(model.chapters.reduce((sum, stage) => sum + stage.refs.length, 0), 224);
  for (const stage of model.chapters) assert.equal(stage.integrated, stage.refs.length);
  await page.setViewportSize({ width: 1440, height: 1100 });
  await page.goto(pathToFileURL(path.join(dir, 'cadeia-de-valor.html')).href, { waitUntil: 'load' });
  await page.waitForFunction(() => window.valueChainApi);
  assert.equal(await page.locator('.value-stage').count(), 6);
  assert.equal(await page.locator('.capability-card').count(), 37);
  assert.equal(await page.locator('.backbone-grid article').count(), 4);
  assert.equal(await page.locator('.topbar [aria-current="page"]').innerText(), 'Cadeia de valor');
  assert(!privateNames.test(await page.locator('body').innerText()));
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  const broken = await page.evaluate(() => [...document.querySelectorAll('a[href^="#"]')].map(anchor => anchor.getAttribute('href').slice(1)).filter(id => !document.getElementById(id)));
  assert.deepEqual(broken, []);
  await page.screenshot({ path: path.join(dir, 'preview-cadeia-de-valor.png') });
  await page.locator('[data-stage-link="0"]').click();
  await page.waitForFunction(() => window.valueChainApi.getState().stage === 0);
  await page.locator('#originacao .expand-stage').click();
  assert.equal(await page.locator('#originacao .capability-card[open]').count(), 5);
  assert.equal(await page.locator('#originacao .expand-stage').getAttribute('aria-expanded'), 'true');
  assert.equal(await page.locator('#originacao .capability-sources a').count(), model.chapters[0].stories.reduce((sum, story) => sum + story.refs.length, 0));
  await page.locator('#originacao .expand-stage').click();
  assert.equal(await page.locator('#originacao .capability-card[open]').count(), 0);
  await page.locator('#originacao .capability-card summary').first().focus();
  await page.keyboard.press('Enter');
  assert.equal(await page.locator('#originacao .capability-card[open]').count(), 1);
  await page.keyboard.press('Enter');
  await page.locator('[data-stage-link="2"]').click();
  assert.equal(new URL(page.url()).hash, '#decisao');
  await page.reload();
  await page.waitForFunction(() => window.valueChainApi.getState().stage === 2, null, { timeout: 5000 }).catch(async error => { throw new Error(JSON.stringify(await page.evaluate(() => ({ state: window.valueChainApi.getState(), hash: location.hash, scroll: scrollY, nav: document.querySelector('.value-nav-wrap').offsetHeight, positions: [...document.querySelectorAll('.value-stage')].map(stage => [stage.id, stage.getBoundingClientRect().top]) }))) + String(error)); });
  await page.locator('[data-stage-link="4"]').click();
  await page.waitForFunction(() => window.valueChainApi.getState().stage === 4);
  await page.screenshot({ path: path.join(dir, 'preview-cadeia-dinheiro.png') });
  await page.evaluate(() => window.valueChainApi.go(0));
  await page.locator('#value-present').click();
  assert.equal(await page.locator('.value-stage:visible').count(), 1);
  await page.keyboard.press('ArrowRight');
  await page.waitForFunction(() => window.valueChainApi.getState().stage === 1);
  assert.equal(await page.locator('#evidencias').isVisible(), true);
  await page.screenshot({ path: path.join(dir, 'preview-cadeia-apresentacao.png') });
  await page.locator('[data-stage-link="5"]').click();
  assert.equal(await page.locator('#value-next').isDisabled(), true);
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('.value-stage:visible').count(), 6);
  await page.evaluate(() => window.valueChainApi.presentation(true));
  await page.locator('#continuidade [data-open-capabilities]').click();
  assert.equal(await page.evaluate(() => window.valueChainApi.getState().presenting), false);
  assert.equal(await page.locator('#frentes-continuidade').isVisible(), true);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.evaluate(() => window.scrollTo(0, 0));
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.screenshot({ path: path.join(dir, 'preview-cadeia-de-valor-mobile.png') });
  for (const stage of model.chapters) {
    await page.locator(`[data-stage-link="${Number(stage.number) - 1}"]`).click();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, stage.id);
    await page.locator('#' + stage.id + ' .expand-stage').click();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, stage.id + ' expandido');
    assert(!privateNames.test(await page.locator('#' + stage.id).innerText()), stage.id);
  }
  await page.evaluate(() => window.valueChainApi.presentation(true));
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, 'apresentação no celular');
  await page.evaluate(() => window.valueChainApi.presentation(false));
  await page.setViewportSize({ width: 1440, height: 1100 });
  await page.evaluate(() => document.querySelectorAll('.capability-card').forEach(item => { item.open = false; }));
  await page.pdf({ path: path.join(dir, 'cadeia-de-valor.pdf'), format: 'A4', printBackground: true, preferCSSPageSize: true, displayHeaderFooter: true, headerTemplate: '<span></span>', footerTemplate: '<div style="width:100%;margin:0 15mm;font:8px sans-serif;color:#5a5468;display:flex;justify-content:space-between"><span>Catalisa · Cadeia de valor</span><span><span class="pageNumber"></span> / <span class="totalPages"></span></span></div>' });
  const file = path.join(dir, 'cadeia-de-valor.pdf');
  const text = execFileSync('pdftotext', [file, '-'], { encoding: 'utf8' });
  assert(!privateNames.test(text));
  const normalized = text.replace(/\s+/g, ' ');
  for (const stage of model.chapters) for (const story of stage.stories) {
    assert(text.replace(/\s/g, '').includes(story.id), story.id + ' ausente no PDF');
    assert(normalized.includes(story.value), story.id + ' sem valor no PDF');
  }
  const pages = Number(execFileSync('pdfinfo', [file], { encoding: 'utf8' }).match(/Pages:\s+(\d+)/)[1]);
  const pageTexts = text.split('\f').filter(value => value.trim());
  assert.equal(pageTexts.length, pages);
  for (let index = 1; index < pageTexts.length; index++) assert(new RegExp(`\\b${index + 1}\\s*/\\s*${pages}\\b`).test(pageTexts[index]));
  return { page: 'cadeia-de-valor', chapters: 6, stories: 37, distinctPrs: 220, presentationKeyboard: true, deepLinks: true, expandableCapabilities: true, mobileOverflow: false, visibleClientNames: false, pdf: { file: 'cadeia-de-valor.pdf', pages, bytes: fs.statSync(file).size, pageNumbers: true, visibleClientNames: false } };
}
